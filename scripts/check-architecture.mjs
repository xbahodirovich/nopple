import assert from 'node:assert/strict';
import { mkdir, readFile } from 'node:fs/promises';
import { chromium } from '@playwright/test';
import { createServer } from 'vite';
const server = await createServer({ server: { port: 5175, host: '127.0.0.1' } });
let browser;
try {
  await server.listen();
  browser = await chromium.launch({ headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto(`http://127.0.0.1:${server.httpServer.address().port}/editor.html`, { waitUntil: 'networkidle' });
  await page.locator('[data-view="3d"]').click();
  await page.locator('#architecture-view').selectOption('cutaway');
  await page.locator('#architecture-dimensions').check();
  await page.locator('.architecture-dimensions text').first().waitFor();
  await page.locator('.measurement-schedule summary').click();
  assert.ok(await page.locator('#measurement-rows tr').count() > 70);
  await page.locator('#measurement-filter').fill('room_that_does_not_exist');
  assert.match(await page.locator('#measurement-rows').textContent(), /No matching/);
  await page.locator('#measurement-filter').fill('Kitchen ·');
  assert.ok(await page.locator('#measurement-rows tr').count() >= 4);
  await page.getByRole('button', { name: 'Kitchen · X extent (centerlines)', exact: true }).click();
  assert.equal(await page.locator('#prop-room-name').inputValue(), 'Kitchen');
  const downloaded = page.waitForEvent('download'); await page.locator('#measurement-export').click();
  const csv = await readFile(await (await downloaded).path(), 'utf8');
  assert.match(csv, /Kitchen/); assert.match(csv, /24.400000,m²/);
  await mkdir('.impeccable/review', { recursive: true });
  await page.screenshot({ path: '.impeccable/review/architecture-desktop.png' });
  await page.locator('.measurement-schedule summary').click();
  await page.locator('#architecture-floor').selectOption({ label: 'Ground floor' });
  const before = await page.locator('#pane-3d canvas').screenshot({path:'/tmp/architecture-before-capture.png'});
  await page.locator('#btn-open-gallery').click();
  await page.locator('#gallery-tab-exterior').click();
  assert.equal(await page.locator('.gallery-card').count(), 5);
  await page.locator('#gallery-btn-capture-all').click();
  assert.equal(await page.locator('.gallery-card img').count(), 5);
  assert.equal(await page.locator('.gallery-card-error').count(), 0);
  for (const image of await page.locator('.gallery-card img').all()) assert.ok(await image.evaluate(img => img.complete && img.naturalWidth === 1280));
  await page.screenshot({ path: '.impeccable/review/exterior-gallery-desktop.png' });
  await page.locator('.btn-card-view').first().click();
  await page.locator('#lightbox-img').screenshot({ path: '.impeccable/review/street-capture.png' });
  await page.locator('#lightbox-close').click();
  console.log('Exterior captures verified');
  const packagePromise = page.waitForEvent('download'); await page.locator('#gallery-btn-export-plan').click();
  const plan = JSON.parse(await readFile(await (await packagePromise).path(), 'utf8'));
  assert.equal(plan.viewpoints.filter(v => v.exteriorView).length, 5);
  assert.ok(plan.viewpoints.filter(v => v.exteriorView).every(v => v.captured));
  assert.ok(plan.viewpoints.every(v => Number.isFinite(v.target.x) && Number.isFinite(v.target.y) && Number.isFinite(v.target.z)), 'exported viewpoints include exact camera targets');
  console.log('Package export verified');
  await page.locator('#gallery-tab-interior').click();
  await page.locator('.btn-card-capture').first().click();
  assert.equal(await page.locator('.gallery-card img').count(), 1);
  await page.locator('#gallery-btn-close').click();
  console.log('Interior capture verified');
  const after = await page.locator('#pane-3d canvas').screenshot({path:'/tmp/architecture-after-capture.png'});
  const delta = await page.evaluate(async ([a, b]) => {
    const images = await Promise.all([a, b].map(src => new Promise(resolve => { const img = new Image(); img.onload = () => resolve(img); img.src = src; })));
    const c = document.createElement('canvas'); c.width = images[0].width; c.height = images[0].height; const ctx = c.getContext('2d');
    ctx.drawImage(images[0], 0, 0); const first = ctx.getImageData(0, 0, c.width, c.height).data;
    ctx.drawImage(images[1], 0, 0); const second = ctx.getImageData(0, 0, c.width, c.height).data;
    let count = 0, minX = c.width, minY = c.height, maxX = 0, maxY = 0;
    for (let i = 0; i < first.length; i += 4) if (first[i] !== second[i] || first[i+1] !== second[i+1] || first[i+2] !== second[i+2]) { const x = i / 4 % c.width, y = Math.floor(i / 4 / c.width); count++; minX = Math.min(minX,x); minY = Math.min(minY,y); maxX = Math.max(maxX,x); maxY = Math.max(maxY,y); }
    return { count, minX, minY, maxX, maxY };
  }, [before, after].map(b => 'data:image/png;base64,' + b.toString('base64')));
  console.log('Screenshot delta', delta);
  assert.ok(delta.count === 0 || (delta.maxX < 430 && delta.maxY < 180), 'capture restores viewport pixels outside the focused controls');
  // A geometry edit invalidates cached exterior images.
  await page.locator('#project-title').fill('Updated house'); await page.locator('#project-title').press('Tab');
  await page.locator('#btn-open-gallery').click(); await page.locator('#gallery-tab-exterior').click();
  assert.equal(await page.locator('.gallery-card img').count(), 0);
  await page.locator('#gallery-btn-close').click();
  await page.locator('#architecture-floor').selectOption('');
  await page.locator('#architecture-view').selectOption('street');
  await page.locator('#architecture-dimensions').uncheck();
  await page.screenshot({ path: '.impeccable/review/street-desktop.png' });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('[data-view="3d"]').click();
  await page.locator('#architecture-view').selectOption('cutaway');
  await page.locator('#hud-reset').click();
  await page.locator('#architecture-dimensions').check();
  await page.locator('.measurement-schedule summary').click();
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  assert.ok(await page.locator('.architecture-controls').evaluate(el => el.scrollWidth <= el.clientWidth));
  await page.screenshot({ path: '.impeccable/review/architecture-mobile.png' });
  await page.locator('.measurement-schedule summary').click();
  await page.screenshot({ path: '.impeccable/review/architecture-mobile-model.png' });
  await page.locator('#btn-open-gallery').click();
  await page.screenshot({ path: '.impeccable/review/exterior-gallery-mobile.png' });
  assert.ok(await page.locator('.gallery-dialog').evaluate(el => el.scrollWidth <= el.clientWidth));
  assert.deepEqual(errors, []);
  console.log('Architecture checks passed: dimensions, selection, CSV, five exterior captures, interior capture, camera restoration, cache invalidation and mobile layout.');
} finally { await browser?.close(); await server.close(); }
